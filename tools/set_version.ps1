# Sets the addon version to now and writes src\Version.h. The date (YYYY.MM.DD) and the time
# (HHMM, 24-hour) are both UTC, so the whole version is in one time zone.
# Version format: YYYY.MM.DD.HHMM.Channel, e.g. 2026.11.21.1430.Dev (docs/design.md, "Versioning").
# Channel: Dev (until initial development is finished), Beta or Rel.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\set_version.ps1 [-Channel Dev|Beta|Rel]
#
# Run it once per release, commit src\Version.h, and tag the GitHub release with the number part
# only (2026.11.21.1430): Nexus ignores tags with a suffix.
param(
    [ValidateSet("Dev", "Beta", "Rel")]
    [string]$Channel = "Dev"
)

$ErrorActionPreference = "Stop"
$now  = [DateTime]::UtcNow
$y    = $now.Year
$m    = $now.Month
$d    = $now.Day
$hhmm = $now.Hour * 100 + $now.Minute
$num  = "{0}.{1:D2}.{2:D2}.{3:D4}" -f $y, $m, $d, $hhmm
$text = "$num.$Channel"

$header = @"
#pragma once

// The addon version. Generated by tools\set_version.ps1; don't edit by hand.
// Format: YYYY.MM.DD.HHMM.Channel; the date and time are both UTC. Channel: Dev, Beta or Rel.
// Included by Globals.h and the .rc
// file (the DLL's File version / Product version in its Properties), so plain #defines only.

#define CHATMSG_VER_YEAR    $y
#define CHATMSG_VER_MONTH   $m
#define CHATMSG_VER_DAY     $d
#define CHATMSG_VER_TIME    $hhmm
#define CHATMSG_VER_CHANNEL "$Channel"
#define CHATMSG_VER_TAG     "$num"
#define CHATMSG_VER_TEXT    "$text"
"@

$path = Join-Path $PSScriptRoot "..\src\Version.h"
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($path), $header.Replace("`r`n", "`n") + "`n")
Write-Output "Version: $text  (GitHub release tag: $num)"
