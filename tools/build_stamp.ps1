# Writes the build stamp header (git commit, uncommitted-changes flag, UTC build time).
# Run by the .vcxproj before every build; the output lives under build\ and is never committed.
# The release version is separate: tools\set_version.ps1 writes src\Version.h once per release.
param([Parameter(Mandatory = $true)][string]$OutFile)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot

$sha   = "unknown"
$dirty = $false
try {
    $s = & git -C $repo rev-parse --short=7 HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and $s) {
        $sha = $s.Trim()
        # Changes to tracked files only: untracked notes in the folder don't count.
        $st = & git -C $repo status --porcelain --untracked-files=no 2>$null
        $dirty = [bool]$st
    }
} catch { }

$time  = [DateTime]::UtcNow.ToString("yyyy-MM-dd HH:mm") + " UTC"
$label = if ($dirty) { "$sha+changes" } else { $sha }
$text  = "$label, $time"

$header = @"
#pragma once

// Build stamp. Generated by tools\build_stamp.ps1 before every build; never commit it.
// The commit is git's short SHA ("+changes" = built with uncommitted edits); the time is UTC.

#define CHATMSG_BUILD_COMMIT "$label"
#define CHATMSG_BUILD_TIME   "$time"
#define CHATMSG_BUILD_TEXT   "$text"
"@

$dir = Split-Path -Parent $OutFile
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
[System.IO.File]::WriteAllText($OutFile, $header + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Build stamp: $text"
